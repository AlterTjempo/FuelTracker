"""Full backtest report of the trend models.

    python -m app.services.trend_backtest --out docs/trend-backtest.md
    python -m services.trend_backtest        # when the working dir is app/

Prints, for every fuel, horizon and candidate variant (out of sample = second
half of the walk-forward backtest): MAE vs. the "no change" baseline,
directional accuracy, pinball loss of the 10% / 90% quantiles, Diebold-Mariano
p-values, and the coverage of the 80% band before and after calibration. It
also reports the probability-of-a-rise model (Brier score vs. base rate,
reliability table) and the hourly forecast (MAE vs. two baselines).
"""

import argparse
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import analytics_config as cfg  # noqa: E402
from services import forecast_model as fm  # noqa: E402


def _f(x, d=2):
    return "–" if x is None else f"{x:.{d}f}"


def collect(fuel: str) -> tuple[dict, dict]:
    from database import SessionLocal
    from routers import insights as ins

    db = SessionLocal()
    try:
        now = datetime.now(timezone.utc)
        since = now - timedelta(days=ins.TREND_LOOKBACK_DAYS)
        days = ins._build_daily(ins._hourly_series(db, ins.FUEL_COLUMNS[fuel], since))
        price = ins._daily_levels(days)
        oil = ins._daily_oil(db, since)
        news = ins._daily_news_scores(db, since)
        market = ins._daily_market(db, since)
        debug: dict = {}
        result = fm.build_trend_forecast(
            price,
            oil,
            news,
            now.astimezone(ins.TZ).date(),
            market=market,
            hourly_days=days,
            debug=debug,
        )
        return result, debug
    finally:
        db.close()


def render(results: dict) -> str:
    L = [
        "# Trend model backtest\n",
        "_Generated by `python -m app.services.trend_backtest`. Do not edit by hand._\n",
    ]
    L.append(
        "All numbers are **out of sample**: each variant is trained walk-forward (only on targets that had already "
        "happened), the first half of the folds selects the model and calibrates the band, and everything below is "
        'measured on the **second half**. Baseline = "the price stays the same". Errors in cents per litre.\n'
    )
    L.append(
        f"Selection rule: skill ≥ {cfg.TREND_MIN_SKILL:.0%} on the selection half **and** Diebold-Mariano p < {cfg.TREND_MAX_DM_P} "
        "(one-sided, Newey-West, h-1 lags, Harvey correction); the model must also beat the baseline on the evaluation half.\n"
    )
    for fuel, (res, dbg) in results.items():
        L.append(f"\n## {fuel.upper()}\n")
        if res["insufficient_data"]:
            L.append(f"Not enough data: {res['reason']}\n")
            continue
        L.append(
            f"Origin {res['origin_date']} · {res['days_used']} usable days · oil {res['oil_days']} d · news {res['news_days']} d · "
            f"market series (days): {', '.join(f'{k} {v}' for k, v in res['market_days'].items()) or 'none'}\n"
        )
        for h in res["horizons"]:
            L.append(
                f"\n### {h['h']} day(s) ahead → used: **{h['model']}** (reliability **{h['reliability']['level']}**: {h['reliability']['why']})\n"
            )
            L.append(
                "| Variant | Folds | MAE | Baseline MAE | Skill (select) | Skill (eval) | DM p (select) | DM p (eval) | Direction acc. (base) | Pinball 10/90 (base) | Band 80% coverage calibrated / raw ±1.28σ |"
            )
            L.append("|---|---:|---:|---:|---:|---:|---:|---:|---|---|---|")
            for name, e in dbg["trend"][h["h"]].items():
                L.append(
                    f"| {name} | {e['n_folds']} | {_f(e['mae_eval'])} | {_f(e['mae_persistence_eval'])} | {_f(e['skill_select'], 3)} | {_f(e['skill_eval'], 3)} | "
                    f"{_f(e['dm_p_select'], 3)} | {_f(e['dm_p_eval'], 3)} | {_f(e['directional_accuracy'], 2)} ({_f(e['directional_base'], 2)}) | "
                    f"{_f(e['pinball10'], 2)}/{_f(e['pinball90'], 2)} ({_f(e['pinball10_base'], 2)}/{_f(e['pinball90_base'], 2)}) | "
                    f"{_f(e['coverage80'], 2)}{'' if e['calibrated'] else ' ⚠'} / {_f(e['coverage80_raw_sigma'], 2)} |"
                )
        p = res["probability"]
        L.append(f"\n### Probability of a rise of more than {p['x_cents']} cent\n")
        L.append(
            "| Horizon | Model | Validated | Brier | Brier (base rate) | Brier skill | DM p (eval) | ECE | Base rate | Folds |"
        )
        L.append("|---|---|---|---:|---:|---:|---:|---:|---:|---:|")
        for e in p["horizons"]:
            L.append(
                f"| {e['hours']} h | {e.get('model') or '–'} | {'yes' if e['validated'] else 'no'} | {_f(e.get('brier'), 4)} | {_f(e.get('brier_base'), 4)} | "
                f"{_f(e.get('brier_skill'), 3)} | {_f(e.get('dm_p_eval'), 3)} | {_f(e.get('ece'), 3)} | {_f(e.get('base_rate'), 3)} | {e.get('n_test', '–')} |"
            )
        for e in p["horizons"]:
            if e.get("reliability_table"):
                L.append(
                    f"\nReliability table, {e['hours']} h (predicted vs. observed frequency, evaluation half):\n"
                )
                L.append("| Predicted bin | Cases | Mean predicted | Observed |")
                L.append("|---|---:|---:|---:|")
                for r in e["reliability_table"]:
                    L.append(
                        f"| {r['bin']} | {r['n']} | {r['mean_predicted']:.2f} | {r['observed']:.2f} |"
                    )
        hh = res.get("hourly", {})
        L.append("\n### Hourly forecast (next day)\n")
        if "mae_cents" in hh:
            L.append(
                f"Variant **{hh['variant']}** · MAE {hh['mae_cents']} ¢ · same hour yesterday {hh['baseline_same_hour_yesterday_mae']} ¢ · "
                f"same hour, same weekday last week {hh['baseline_same_hour_last_week_mae']} ¢ · DM p vs. better baseline {_f(hh['dm_p_vs_best_baseline'], 3)} · "
                f"{hh['n_test_days']} test days · **{'validated' if hh['validated'] else 'not validated'}** (needs MAE below both baselines and DM p < {cfg.TREND_MAX_DM_P}).\n"
            )
        else:
            L.append(f"Not evaluated: {hh.get('reason')}\n")
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--fuel",
        nargs="+",
        default=["e5", "e10", "diesel"],
        choices=["e5", "e10", "diesel"],
    )
    ap.add_argument("--out", default=None)
    args = ap.parse_args(argv)
    results = {f: collect(f) for f in args.fuel}
    md = render(results)
    if args.out:
        Path(args.out).write_text(md)
        print(f"report written to {args.out}")
    else:
        print(md)


if __name__ == "__main__":
    main()
